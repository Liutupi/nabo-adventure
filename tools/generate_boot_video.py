"""Validate the explicitly selected, immutable video and emit flash-backed C data."""
import argparse,json,re
from pathlib import Path
from adventure_assets_manifest import scoped,digest
ROOT=Path(__file__).resolve().parents[1];ART=ROOT/'game-art/adventure/art'
LIMIT=224*1024
def stream(data,frames):
 if len(data)<12 or data[:4]!=b'\0\0\1\xb3':raise ValueError('Missing MPEG sequence')
 headers=list(re.finditer(b'\x00\x00\x01\xb3',data))
 for m in headers:
  p=m.end()
  if len(data)-p<4 or ((data[p]<<4)|(data[p+1]>>4),(data[p+1]&15)<<8|data[p+2])!=(208,272) or data[p+3]&15!=2:raise ValueError('MPEG dimensions/rate differ')
 pictures=list(re.finditer(b'\x00\x00\x01\x00',data))
 if len(pictures)!=frames:raise ValueError('MPEG frame count differs')
 types=[]
 for m in pictures:
  if len(data)-m.end()<4:raise ValueError('Truncated picture header')
  t=data[m.end()+1]>>3&7
  if t not in (1,2):raise ValueError('Only MPEG I/P frames supported')
  types.append(t)
 if not types or types[0]!=1:raise ValueError('First MPEG frame must be intra')
 if data[-4:]!=b'\0\0\1\xb7':raise ValueError('Missing MPEG sequence end')
 return types
def read_video(art=ART):
 art=Path(art).resolve();sel=art/'boot/selection.json'
 if not sel.exists():return None
 selection=json.loads(scoped(art,'boot/selection.json').read_text('utf-8'))
 if selection.get('kind')!='mpeg1-ip':return None
 if type(selection.get('version')) is not int or selection['version']!=1:raise ValueError('Unsupported boot selection')
 path=scoped(art,selection['manifest'])
 if digest(path)!=selection['sha256']:raise ValueError('Video manifest SHA256 mismatch')
 v=json.loads(path.read_text('utf-8'))
 if v['schema']!='adventure-boot-mpeg1-ip-v1' or v['runtime_canvas']!=[208,272] or v['display_canvas']!=[240,320] or type(v['logical_fps']) is not int or v['logical_fps']!=12 or v['header_fps']!=24:raise ValueError('Unsupported boot video profile')
 deps={'boot/selection.json':digest(sel),path.relative_to(art).as_posix():digest(path)}
 for name,count in [('movie',73),('poster',1)]:
  media=v[name];p=scoped(art,media['path']);data=p.read_bytes()
  if media['frames']!=count or type(media['frames']) is not int or len(data)!=media['bytes'] or digest(p)!=media['sha256']:raise ValueError('Video bytes/SHA256/frame count differ')
  stream(data,count);deps[media['path']]=digest(p)
 for relative,sha in v['source_sha256'].items():
  p=scoped(art,relative)
  if digest(p)!=sha:raise ValueError('Video source SHA256 mismatch')
  deps[relative]=sha
 t=v['timeline']
 if t['total_duration_ms']!=6600 or t['terminal_frame']!=72 or t['terminal_hold_ms']!=600:raise ValueError('Video final hold must retain actual final frame')
 from generate_boot_presentation import voice_contract
 _,_,voice=voice_contract(art,v,t,t['total_duration_ms']);deps['../'+voice.relative_to(art.parent).as_posix()]=digest(voice)
 if v['opening_budget']['limit_bytes']!=LIMIT:raise ValueError('Invalid video opening budget')
 return {'value':v,'dependencies':deps,'bytes':sum(v[k]['bytes'] for k in ('movie','poster'))+32,'art':art}
def generate(art=ART,output=ROOT/'firmware/main/generated'):
 art=Path(art).resolve();output=Path(output).resolve();v=read_video(art);output.mkdir(parents=True,exist_ok=True)
 header=['// Generated by tools/generate_boot_video.py','#pragma once','#include <stddef.h>','#include <stdint.h>',f'#define ADV_BOOT_VIDEO_ENABLED {int(v is not None)}u','#define ADV_BOOT_VIDEO_DURATION_MS 6600u','#define ADV_BOOT_VIDEO_FPS 12u','#define ADV_BOOT_VIDEO_FRAMES 73u']
 code=['// Generated by tools/generate_boot_video.py','#include "adv_boot_video_data.h"']
 for name in ('movie','poster'):
  data=(art/v['value'][name]['path']).read_bytes() if v else b'\0'
  symbol='adv_boot_video_'+name
  header += [f'extern const uint8_t {symbol}[];',f'extern const size_t {symbol}_bytes;']
  code += [f'const uint8_t {symbol}[] = {{']+['    '+','.join(str(n) for n in data[i:i+32])+',' for i in range(0,len(data),32)]+['};',f'const size_t {symbol}_bytes = sizeof({symbol});']
 if v:
  for relative,expected in v['dependencies'].items():
   if digest(art/relative)!=expected:raise ValueError('Video source changed during generation')
 for name,lines in [('adv_boot_video_data.h',header),('adv_boot_video_data.c',code)]:
  p=output/name;temp=p.with_suffix(p.suffix+'.tmp');temp.write_text('\n'.join(lines)+'\n','utf-8',newline='\n');temp.replace(p)
 return {'enabled':v is not None,'media_bytes':v['bytes'] if v else 0}
if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--art',type=Path,default=ART);ap.add_argument('--output',type=Path,default=ROOT/'firmware/main/generated');a=ap.parse_args();print(json.dumps(generate(a.art,a.output),indent=2))
